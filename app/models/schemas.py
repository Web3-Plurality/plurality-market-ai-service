from pydantic import BaseModel
from typing import Optional, List

class ContextRequest(BaseModel):
    userId: str
    profileId: str
    context: str
    contextId: str  # Context ID generated by backend-api

class QueryRequest(BaseModel):
    userId: str
    profileId: str
    query: str
    k: Optional[int] = 5
    chatHistory: Optional[List[dict]] = []  # Add chat history support
    contextSummary: Optional[List[str]] = []
    enableWebSearch: Optional[bool] = False  # Filter for web search
    enableUrlExtraction: Optional[bool] = False  # Filter for URL extraction
    model: Optional[str] = "gemini"  # Model identifier (gemini or bedrock model key)



class RagQueryRequest(BaseModel):
    userId: str
    profileId: Optional[str] = ""
    query: str
    k: Optional[int] = 5
    chatHistory: Optional[List[dict]] = []  # Add chat history support
    contextSummary: Optional[List[str]] = []
    attachContextSummary: Optional[bool] = True  # Filter for URL extraction
    platform: Optional[str] = "chatGPT"


class ContextResponse(BaseModel):
    message: str
    contextId: str
    chunks: int
    createdAt: str
    extractedTitle: str
    extractedDescription: str  # Add extracted description to response
    vectorIds: List[str]  # Vector IDs stored in S3 Vectors

class FileUploadResponse(BaseModel):
    message: str
    contextId: str
    fileName: str
    fileType: str
    chunks: int
    createdAt: str
    extractedTitle: str
    extractedDescription: str  # Add extracted description to response

# New schema models for chat history endpoint
class ChatMessage(BaseModel):
    role: str  # "user", "assistant", etc.
    content: str

class AddRagContextRequest(BaseModel):
    userId: str
    profileId: str
    chatHistory: List[ChatMessage]
    contextId: str  # Context ID generated by backend-api

class AddRagContextResponse(BaseModel):
    message: str
    contextId: str
    chunks: int
    createdAt: str
    extractedTitle: str
    extractedDescription: str
    extractedInsights: str  # Insights and user info extracted from chat
    vectorIds: List[str]  # Vector IDs stored in S3 Vectors

class SimilaritySearchRequest(BaseModel):
    userId: str
    profileId: str
    query: str
    k: Optional[int] = 5

class SimilarityResult(BaseModel):
    content: str
    metadata: dict
    distance: float
    similarity_score: float

class SimilaritySearchResponse(BaseModel):
    query: str
    userId: str
    profileId: str
    total_results: int
    results: List[SimilarityResult]

class DeleteContextRequest(BaseModel):
    userId: str
    contextId: str  # The ID of the context/file to delete

class DeleteContextResponse(BaseModel):
    message: str
    contextId: str
    deletedVectors: int

class GetContextDataResponse(BaseModel):
    contextId: str
    title: str
    contentType: str
    totalChunks: int
    content: str
    nextChunk: Optional[int] = None

class DeleteAllContextsRequest(BaseModel):
    userId: str
    profileId: str

class DeleteAllContextsResponse(BaseModel):
    message: str
    userId: str
    profileId: str
    deletedVectors: int
 