from fastapi import APIRouter, HTTPException, Depends, UploadFile, File, Form
from typing import Optional, List

from app.models.schemas import (
    ContextRequest, ContextResponse, FileUploadResponse,
    SimilaritySearchRequest, SimilaritySearchResponse,
    AddRagContextRequest, AddRagContextResponse,
    DeleteContextRequest, DeleteContextResponse,
    DeleteAllContextsRequest, DeleteAllContextsResponse,
    GetContextDataResponse,
)
from app.api.dependencies import validate_api_key
from app.services.context_service import context_service
from app.services.vector_service import vector_service

# Create router for context endpoints
context_router = APIRouter(prefix="/rag", tags=["rag"])

@context_router.post("/add-context", response_model=ContextResponse)
async def add_context(
    context_request: ContextRequest,
    _api_key: str = Depends(validate_api_key)
):
    """
    Add a raw context to the user's verctorDB knowledge base and returns Title, Summary (Used by: Dashboard)

    Headers:
    - X-API-Key: API key for authentication

    Body:
    - userId: User's unique identifier
    - profileId: Profile's unique identifier
    - context: Text content to add to the knowledge base
    """
    return await context_service.add_context(context_request)

@context_router.post("/upload-file", response_model=FileUploadResponse)
async def upload_file(
    file: UploadFile = File(...),
    userId: str = Form(...),
    profileId: str = Form(...),
    contextId: str = Form(...),
    _api_key: str = Depends(validate_api_key)
):
    """
    Upload and process a file (TXT, DOCX, PDF, MD, JSON) AND adds context to user vectorDB knowledge base, returns Title, Summary (Used by: Dashboard)

    Headers:
    - X-API-Key: API key for authentication

    Form Data:
    - file: File to upload (max 10MB)
    - userId: User's unique identifier
    - profileId: Profile's unique identifier
    - contextId: Context ID generated by backend-api
    """
    return await context_service.upload_file(file=file, userId=userId, profileId=profileId, contextId=contextId)

@context_router.post("/add-rag-context", response_model=AddRagContextResponse)
async def add_rag_context(
    rag_request: AddRagContextRequest,
    _api_key: str = Depends(validate_api_key)
):
    """
    Process chat history to extract insights and user information, then save to vectorDB and returns the Title, Summary (For extension)

    Headers:
    - X-API-Key: API key for authentication

    Body:
    - userId: User's unique identifier
    - profileId: Profile's unique identifier
    - chatHistory: Array of chat messages with role and content
    """
    return await context_service.add_rag_context(rag_request)



@context_router.post("/similarity-search", response_model=SimilaritySearchResponse)
async def similarity_search(
    search_request: SimilaritySearchRequest,
    _api_key: str = Depends(validate_api_key)
):
    """
    Perform similarity search without LLM processing (No external tool uses it)
    
    Headers:
    - X-API-Key: API key for authentication
    
    Body:
    - userId: User's unique identifier
    - profileId: Profile's unique identifier
    - query: Search query text
    - k: Number of similar results to return (optional, default: 5)
    """
    return vector_service.similarity_search(search_request=search_request, chunk_content_store=context_service.chunk_content_store)

@context_router.delete("/delete-context", response_model=DeleteContextResponse)
async def delete_context(
    userId: str,
    contextId: str,
    _api_key: str = Depends(validate_api_key)
):
    """
    Delete a context and all associated vectors from the system (Used by: Dashboard)

    Headers:
    - X-API-Key: API key for authentication

    Query Parameters:
    - userId: User's unique identifier
    - contextId: The ID of the context/file to delete
    """
    # Construct DeleteContextRequest from query parameters
    delete_request = DeleteContextRequest(
        userId=userId,
        contextId=contextId
    )
    return await context_service.delete_context(delete_request)

@context_router.delete("/delete-all-contexts", response_model=DeleteAllContextsResponse)
async def delete_all_contexts(
    userId: str,
    profileId: str,
    _api_key: str = Depends(validate_api_key)
):
    """
    Delete all contexts and all associated vectors for a given userId and profileId (Used by: Dashboard)

    Headers:
    - X-API-Key: API key for authentication

    Query Parameters:
    - userId: User's unique identifier
    - profileId: Profile's unique identifier
    """
    # Construct DeleteAllContextsRequest from query parameters
    delete_request = DeleteAllContextsRequest(
        userId=userId,
        profileId=profileId
    )
    return await context_service.delete_all_contexts(delete_request)

@context_router.get("/get-context-data", response_model=GetContextDataResponse)
async def get_context_data(
    userId: str,
    contextId: str,
    startChunk: int = 0,
    limit: int = 20,
    _api_key: str = Depends(validate_api_key)
):
    """
    Get context content with pagination support.

    Headers:
    - X-API-Key: API key for authentication

    Query Parameters:
    - userId: User's unique identifier
    - contextId: The ID of the context/file to retrieve
    - startChunk: Chunk index to start from (default: 0)
    - limit: Max number of chunks to return (default: 20, adjust based on agent context window)
    """
    return await context_service.get_context_data(context_id=contextId, user_id=userId, start_chunk=startChunk, limit=limit)